"use client";
import { useEffect, useMemo, useRef, useState, type ReactNode } from "react";
import { codeArtifacts, previewDocument } from "./artifacts";
import { finalAnswer } from "./answer";

/** Keep a native link alive for the artifact's lifetime, including repeated saves. */
function FileLink({ blob, name, children }: { blob: Blob; name: string; children: ReactNode }) {
  const link = useRef<HTMLAnchorElement>(null);
  useEffect(() => {
    const url = URL.createObjectURL(blob);
    if (link.current) link.current.href = url;
    return () => URL.revokeObjectURL(url);
  }, [blob]);
  return <a ref={link} download={name}>{children}</a>;
}

export function ArtifactCards({ text, imageUrl, compact = false }: { text: string; imageUrl?: string; compact?: boolean }) {
  const content = finalAnswer(text);
  // A regenerated answer must never reuse a document prepared for older text.
  return <ArtifactContents key={content} content={content} imageUrl={imageUrl} compact={compact} />;
}

function ArtifactContents({ content, imageUrl, compact }: { content: string; imageUrl?: string; compact: boolean }) {
  const [preview, setPreview] = useState<number | null>(null);
  const [busy, setBusy] = useState("");
  const [error, setError] = useState("");
  const [prepared, setPrepared] = useState<Record<string, Blob>>({});
  const active = useRef(false);
  const preparing = useRef(false);
  useEffect(() => {
    active.current = true;
    return () => { active.current = false; };
  }, []);
  const markdown = useMemo(() => new Blob([content], { type: "text/plain;charset=utf-8" }), [content]);
  const files = useMemo(() => codeArtifacts(content).map(file => ({ ...file, blob: new Blob([file.content], { type: "text/plain;charset=utf-8" }) })), [content]);
  const exportDocument = async (format: "docx" | "pdf") => {
    if (preparing.current) return;
    preparing.current = true;
    setBusy(format); setError("");
    try {
      const tools = await import("./document-tools");
      const blob = await (format === "docx" ? tools.exportDocx(content) : tools.exportPdf(content));
      // Preparation may outlive a user gesture. Offer a native download link
      // instead of a synthetic click that browsers can silently discard.
      if (active.current) setPrepared(current => ({ ...current, [format]: blob }));
    } catch (cause) {
      const message = cause instanceof Error ? cause.message : "";
      if (active.current) setError(/fetch dynamically imported module|importing a module/i.test(message)
        ? "The document exporter could not load. Refresh the page and retry, or download Markdown."
        : message || "Download failed. Please try again.");
    }
    finally { preparing.current = false; if (active.current) setBusy(""); }
  };
  return <div className="artifact-cards">
    {imageUrl ? <figure className="image-artifact">
      {/* Local generated PNGs must not use the unavailable image optimizer. */}
      {/* eslint-disable-next-line @next/next/no-img-element */}
      <img src={imageUrl} alt="Image generated by Ounumi from your request" width={512} height={512} />
      <figcaption><a href={imageUrl} download="ounumi-image.png">Download PNG</a><span>Available in this tab until you clear or reload.</span></figcaption>
    </figure> : null}
    {files.map((file, i) => <section className="artifact-card" key={`${i}-${file.name}`}>
      <div><strong>{file.name}</strong><span>Generated source · review before use</span></div>
      <div className="artifact-controls"><FileLink blob={file.blob} name={file.name}>Download {file.name.split(".").at(-1)?.toUpperCase()}</FileLink>
        {file.language === "html" ? <button type="button" onClick={() => setPreview(preview === i ? null : i)}>{preview === i ? "Close preview" : "Preview"}</button> : null}</div>
      {preview === i ? <iframe title={`Preview ${file.name}`} sandbox="allow-scripts" referrerPolicy="no-referrer" srcDoc={previewDocument(file.content)} /> : null}
    </section>)}
    {!imageUrl && !compact ? <div className="document-exports" aria-label="Download response">
      <FileLink blob={markdown} name="archindus-response.md">Download Markdown</FileLink>
      {(["docx", "pdf"] as const).map(format => prepared[format]
        ? <FileLink key={format} blob={prepared[format]} name={`archindus-document.${format}`}>Download {format.toUpperCase()}</FileLink>
        : <button key={format} type="button" disabled={Boolean(busy)} onClick={() => void exportDocument(format)}>{busy === format ? `Preparing ${format.toUpperCase()}…` : `Prepare ${format.toUpperCase()}`}</button>)}
    </div> : null}
    {Object.keys(prepared).length ? <p className="file-help" role="status">{Object.keys(prepared).map(format => format.toUpperCase()).join(" and ")} ready. Select Download to save.</p> : null}
    {error ? <p className="runtime-error" role="alert">{error}</p> : null}
  </div>;
}
